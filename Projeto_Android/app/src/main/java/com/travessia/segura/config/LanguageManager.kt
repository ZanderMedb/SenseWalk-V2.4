/**
 * Gerenciador simples de idioma do app.
 * Mantém todos os textos visíveis e falas em PT/EN/ES sem alterar a lógica da IA.
 */
object LanguageManager {
    const val PT = "pt"
    const val EN = "en"
    const val ES = "es"

    private const val PREFS_NAME = "travessia_config"
    private const val KEY_LANGUAGE = "app_language"

    data class LanguageOption(val code: String, val label: String)

    val options = listOf(
        LanguageOption(PT, "Português"),
        LanguageOption(EN, "English"),
        LanguageOption(ES, "Español")
    )

    fun deviceDefaultLanguage(): String {
        return when (Locale.getDefault().language.lowercase(Locale.ROOT)) {
            "en" -> EN
            "es" -> ES
            else -> PT
        }
    }

    fun currentLanguage(context: Context): String {
        val prefs = context.getSharedPreferences(PREFS_NAME, Context.MODE_PRIVATE)
        return prefs.getString(KEY_LANGUAGE, deviceDefaultLanguage()) ?: deviceDefaultLanguage()
    }

    fun setLanguage(context: Context, code: String) {
        val safeCode = if (code in options.map { it.code }) code else PT
        context.getSharedPreferences(PREFS_NAME, Context.MODE_PRIVATE)
            .edit()
            .putString(KEY_LANGUAGE, safeCode)
            .apply()
    }

    fun text(context: Context, key: String): String = text(currentLanguage(context), key)

    fun text(code: String, key: String): String {
        val safeCode = if (code in listOf(PT, EN, ES)) code else PT
        val extra = extraTranslations[safeCode].orEmpty()
        val extraFallback = extraTranslations[PT].orEmpty()
        val lang = translations[safeCode] ?: translations[PT].orEmpty()
        return extra[key] ?: lang[key] ?: extraFallback[key] ?: translations[PT]?.get(key) ?: key
    }

